"""Writes src/sim/gates_table.inc, the realm's gate tables, from each world's manifest.

The order plan's sprint D (docs/order-plan.md): a world's gates are its manifest's `gates`
(source/world/<w>/world.json), each row with its citation as a note. The realm keeps them compiled
in -- the server, every mirror and netbot must hold the same table bit for bit, and a table built
into the binary cannot drift between them -- so this script turns the manifests into the C++ that
src/sim/gates.cpp includes, and `./mu check` fails when the two disagree.

    python3 pipeline/gates_table.py            write it (./mu make gates does)
    python3 pipeline/gates_table.py --check    exit 1 when it is not what the manifests say

A row:
    exits:  {"number", "box": [x1, y1, x2, y2], "faces": [dx, dy], "note"}
    enters: {"number", "box", "level", "target", "sealed"?: "place", "fly"?: true, "note"}
The worlds in MU's map order, each world's rows in its manifest's order.
"""
import sys
from pathlib import Path

import world_manifest

OUT = Path(__file__).resolve().parent.parent / "src" / "sim" / "gates_table.inc"

HEAD = """\
// Generated by pipeline/gates_table.py from each world's manifest (source/world/<w>/world.json,
// `gates`), where every row's citation is. Do not edit: edit the manifest, then `./mu make gates`.
// Included by src/sim/gates.cpp alone.
"""


def box(row) -> str:
    x1, y1, x2, y2 = row["box"]
    return f"{{{x1}, {y1}, {x2}, {y2}}}"


def table() -> str:
    worlds = sorted(world_manifest.manifests().items(), key=lambda item: item[1]["map"])
    exits, enters = [], []
    for world, doc in worlds:
        gates = doc.get("gates", {})
        number = doc["map"]
        for row in gates.get("exits", []):
            dx, dy = row["faces"]
            exits.append(f"    {{{row['number']}, {number}, {box(row)}, {dx}, {dy}}},  // {world}")
        for row in gates.get("enters", []):
            tail = ""
            if row.get("sealed") or row.get("fly"):
                sealed = f'"{row["sealed"]}"' if row.get("sealed") else "nullptr"
                tail = f", {sealed}, {'true' if row.get('fly') else 'false'}"
            enters.append(f"    {{{row['number']}, {number}, {box(row)}, {row['level']}, "
                          f"{row['target']}{tail}}},  // {world}")
    return (HEAD + "\nconstexpr ExitGate kExits[] = {\n" + "\n".join(exits) + "\n};\n"
            + "\nconstexpr EnterGate kEnters[] = {\n" + "\n".join(enters) + "\n};\n")


def main():
    text = table()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("gates: src/sim/gates_table.inc is not what the manifests say; `./mu make gates`")
            sys.exit(1)
        print(f"gates: src/sim/gates_table.inc agrees with the manifests")
        return
    if OUT.exists() and OUT.read_text() == text:
        print("gates: src/sim/gates_table.inc already agrees")
        return
    OUT.write_text(text)
    print(f"gates: wrote {OUT.relative_to(OUT.parent.parent.parent)}")


if __name__ == "__main__":
    main()
