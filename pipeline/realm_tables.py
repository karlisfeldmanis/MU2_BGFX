"""Writes the realm's compiled tables from each world's manifest: src/sim/gates_table.inc (the
gates) and src/sim/maps_table.inc (the world table, sim::MapRow); and from each monster's
recipe, src/sim/breeds_table.inc (the breeds' rules, sim/realm_tuning.h).

The order plan's sprint D (docs/plans/order-plan.md): a world's gates are its manifest's `gates` and
its rules its `rules` (content/world/<w>/world.json), each row with its citation as a note. The
realm keeps them compiled in -- the server, every mirror and netbot must hold the same tables
bit for bit, and a table built into the binary cannot drift between them -- so this script turns
the manifests into the C++ that src/sim/gates.cpp and src/sim/maps.cpp include, and `./mu check`
fails when they disagree.

    python3 pipeline/realm_tables.py            write them (./mu make realm does)
    python3 pipeline/realm_tables.py --check    exit 1 when one is not what the manifests say

A gate row:
    exits:  {"number", "box": [x1, y1, x2, y2], "faces": [dx, dy], "note"}
    enters: {"number", "box", "level", "target", "sealed"?: "place", "fly"?: true, "note"}
The gates in MU's map order, each world's rows in its manifest's order.

A world's rules: {"arrive": [column, row], "home": map, "event", "floors", "move_order",
"summons"?: false, "drops"?: ["feather", "nova_scroll", "firecracker", "first_wings",
"second_gear"], "invasion"?: true, "treasure"?: "map" | "last_floor", "flight"?: true,
"second_class"?: true, "note"}.
The world table in `move_order`, which is the M key's walk (sim::mapAfter); a manifest with no
`rules` (the character screen's) is not a world anyone stands in.

A breed's rules (sprint E1), its recipe's `rules` (content/monsters/<Name>.json, joined by
`object_type`), or content/monsters/unbuilt.json's for a breed with no recipe yet:
    {"drops"?: {"money_rate", "max_plus", "regen"}, "resist"?: {"ice", "poison"},
     "poisons"?: true, "bleeds"?: true, "burns"?: true, "chill_odds"?: n, "bolt"?: "some" | "every", "boss"?: true,
     "split"?: {"parts", "melee_first", "after", "every"}, "bulk"?: tiles, "note"}
Each list in breed number order; sim/realm_tuning.h says what each means.
"""
import json
import sys
from pathlib import Path

import world_manifest

# The folders are tools/paths.py's; appended, so nothing there shadows a module here.
sys.path.append(str(Path(__file__).resolve().parents[1] / "tools"))
from paths import P  # noqa: E402

SIM = P.ROOT / "src" / "sim"
MONSTERS = P.CONTENT / "monsters"

HEAD = """\
// Generated by pipeline/realm_tables.py from each world's manifest (content/world/<w>/world.json,
// `{block}`), where every row's citation is. Do not edit: edit the manifest, then `./mu make realm`.
// Included by src/sim/{owner} alone.
"""


def by_map():
    return sorted(world_manifest.manifests().items(), key=lambda item: item[1]["map"])


def box(row) -> str:
    x1, y1, x2, y2 = row["box"]
    return f"{{{x1}, {y1}, {x2}, {y2}}}"


def gates() -> str:
    exits, enters = [], []
    for world, doc in by_map():
        table = doc.get("gates", {})
        number = doc["map"]
        for row in table.get("exits", []):
            dx, dy = row["faces"]
            exits.append(f"    {{{row['number']}, {number}, {box(row)}, {dx}, {dy}}},  // {world}")
        for row in table.get("enters", []):
            tail = ""
            if row.get("sealed") or row.get("fly"):
                sealed = f'"{row["sealed"]}"' if row.get("sealed") else "nullptr"
                tail = f", {sealed}, {'true' if row.get('fly') else 'false'}"
            enters.append(f"    {{{row['number']}, {number}, {box(row)}, {row['level']}, "
                          f"{row['target']}{tail}}},  // {world}")
    return (HEAD.format(block="gates", owner="gates.cpp")
            + "\nconstexpr ExitGate kExits[] = {\n" + "\n".join(exits) + "\n};\n"
            + "\nconstexpr EnterGate kEnters[] = {\n" + "\n".join(enters) + "\n};\n")


def flag(value) -> str:
    return "true" if value else "false"


DROPS = ("feather", "nova_scroll", "firecracker", "first_wings", "second_gear", "kanturu_gear",
         "ancient_runes")
TREASURE = {None: "None", "map": "Map", "last_floor": "LastFloor"}


def maps() -> str:
    worlds = [(world, doc) for world, doc in world_manifest.manifests().items() if "rules" in doc]
    worlds.sort(key=lambda item: item[1]["rules"]["move_order"])
    rows = []
    for world, doc in worlds:
        rules = doc["rules"]
        column, row = rules["arrive"]
        drops = rules.get("drops", [])
        unknown = [drop for drop in drops if drop not in DROPS] + \
            ([rules["treasure"]] if rules.get("treasure") not in TREASURE else [])
        if unknown:
            sys.exit(f"realm: {world}'s rules name {unknown}, which the table does not know")
        fields = [f'.world = "{world}"', f'.number = {doc["map"]}', f'.arrive = {{{column}, {row}}}',
                  f'.home = {rules["home"]}', f'.event = {flag(rules["event"])}',
                  f'.floors = {flag(rules["floors"])}', f'.summons = {flag(rules.get("summons", True))}',
                  f'.feather = {flag("feather" in drops)}', f'.novaScroll = {flag("nova_scroll" in drops)}',
                  f'.invasion = {flag(rules.get("invasion", False))}',
                  f'.firecracker = {flag("firecracker" in drops)}',
                  f'.treasure = Treasure::{TREASURE[rules.get("treasure")]}',
                  f'.flight = {flag(rules.get("flight", False))}',
                  f'.firstWings = {flag("first_wings" in drops)}',
                  f'.secondGear = {flag("second_gear" in drops)}',
                  f'.secondClass = {flag(rules.get("second_class", False))}']
        # Written only where a map has one, so every other row reads as before.
        if rules.get("exp_bonus", 1.0) != 1.0:
            fields.append(f'.expBonus = {float(rules["exp_bonus"])}')
        if "kanturu_gear" in drops:
            fields.append(f'.kanturuGear = true')
        if "ancient_runes" in drops:
            fields.append(f'.ancientRunes = true')
        rows.append("    {" + ", ".join(fields) + "},")
    return (HEAD.format(block="rules", owner="maps.cpp")
            + "\nconstexpr MapRow kMaps[] = {\n" + "\n".join(rows) + "\n};\n")


BREED_KEYS = {"drops", "resist", "poisons", "bleeds", "burns", "chill_odds", "bolt", "boss", "split", "bulk", "note"}


def breed_rules() -> dict:
    """{number: (name, rules)} from every recipe that has `rules`, and unbuilt.json."""
    found = {}

    def take(number, name, rules, where):
        if number in found:
            sys.exit(f"realm: breed {number} has rules in {found[number][2]} and {where}")
        unknown = set(rules) - BREED_KEYS
        if rules.get("bolt") not in (None, "some", "every"):
            unknown.add(f"bolt {rules['bolt']}")
        if unknown:
            sys.exit(f"realm: {where}'s rules name {sorted(unknown)}, which the table does not know")
        found[number] = (name, rules, where)

    for path in sorted(MONSTERS.glob("*.json")):
        if path.name.endswith(".rig.json") or path.name == "unbuilt.json":
            continue
        doc = json.loads(path.read_text())
        if "rules" in doc and "object_type" in doc:
            take(doc["object_type"], doc.get("mu_name", path.stem), doc["rules"], path.name)
    unbuilt = MONSTERS / "unbuilt.json"
    if unbuilt.exists():
        for one in json.loads(unbuilt.read_text())["breeds"]:
            take(one["number"], one["name"], one["rules"], "unbuilt.json")
    return {number: (name, rules) for number, (name, rules, _) in sorted(found.items())}


def breeds() -> str:
    rows = breed_rules()
    lists = {name: [] for name in ("kPoisoners", "kBleeders", "kBurners", "kBoltBlowers", "kEveryBoltBlowers", "kChillers",
                                   "kBosses", "kSplitBlows", "kResistances", "kDropRates", "kBulks")}
    for number, (name, r) in rows.items():
        tag = f"  // {name}"
        if r.get("poisons"):
            lists["kPoisoners"].append(f"    {number},{tag}")
        if r.get("bleeds"):
            lists["kBleeders"].append(f"    {number},{tag}")
        if r.get("burns"):
            lists["kBurners"].append(f"    {number},{tag}")
        if r.get("bolt") == "some":
            lists["kBoltBlowers"].append(f"    {number},{tag}")
        if r.get("bolt") == "every":
            lists["kEveryBoltBlowers"].append(f"    {number},{tag}")
        if "chill_odds" in r:
            lists["kChillers"].append(f"    {{{number}, {r['chill_odds']}}},{tag}")
        if r.get("boss"):
            lists["kBosses"].append(f"    {number},{tag}")
        if "split" in r:
            s = r["split"]
            lists["kSplitBlows"].append(f"    {{{number}, {s['parts']}, {flag(s['melee_first'])}, "
                                        f"{s['after']}, {s['every']}}},{tag}")
        if "resist" in r:
            lists["kResistances"].append(f"    {{{number}, {r['resist']['ice']}, {r['resist']['poison']}}},{tag}")
        if "drops" in r:
            d = r["drops"]
            lists["kDropRates"].append(f"    {{{number}, {d['money_rate']}, {d['max_plus']}, {d['regen']}}},{tag}")
        if "bulk" in r:
            lists["kBulks"].append(f"    {{{number}, {r['bulk']}}},{tag}")
    types = {"kPoisoners": "int32_t", "kBleeders": "int32_t", "kBurners": "int32_t", "kBoltBlowers": "int32_t", "kEveryBoltBlowers": "int32_t",
             "kChillers": "Chiller", "kBosses": "int32_t", "kSplitBlows": "SplitBlow",
             "kResistances": "Resistance", "kDropRates": "DropRate", "kBulks": "Bulk"}
    out = ["// Generated by pipeline/realm_tables.py from each monster's recipe",
           "// (content/monsters/<Name>.json `rules`, and unbuilt.json), where every row's citation is.",
           "// Do not edit: edit the recipe, then `./mu make realm`. Included by src/sim/realm_tuning.h alone."]
    for name, body in lists.items():
        if not body:
            sys.exit(f"realm: no breed fills {name}; C++ has no empty array")
        out.append(f"\nconstexpr {types[name]} {name}[] = {{\n" + "\n".join(body) + "\n};")
    return "\n".join(out) + "\n"


TABLES = [(SIM / "gates_table.inc", gates), (SIM / "maps_table.inc", maps),
          (SIM / "breeds_table.inc", breeds)]


def main():
    check = "--check" in sys.argv
    stale = []
    for path, build in TABLES:
        text = build()
        name = f"src/sim/{path.name}"
        if path.exists() and path.read_text() == text:
            print(f"realm: {name} agrees with the manifests")
        elif check:
            stale.append(name)
        else:
            path.write_text(text)
            print(f"realm: wrote {name}")
    if stale:
        print(f"realm: {', '.join(stale)} not what the manifests say; `./mu make realm`")
        sys.exit(1)


if __name__ == "__main__":
    main()
