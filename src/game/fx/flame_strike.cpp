float FlameStrike::unit() {
    dice_ ^= dice_ << 13;
    dice_ ^= dice_ >> 17;
    dice_ ^= dice_ << 5;
    return float(dice_ & 0xFFFFFFu) / float(0x1000000u);
}

bool FlameStrike::open(const std::string& assetDir, content::Textures& textures,
                       const content::Showing& table, const content::Ground* ground) {
    ground_ = ground;
    const std::string dir = assetDir + "/effects/flame_strike/";
    const auto take = [&](const std::string& path) -> bgfx::TextureHandle {
        if (!core::fileExists(path)) return BGFX_INVALID_HANDLE;
        return textures.load(path, content::TextureRole::Albedo);
    };
    const char* poses[2] = {"FlameStrike_00.obj", "FlameStrike_05.obj"};
    for (int p = 0; p < 2; ++p) {
        blade_[p].clear();
        loadEffectObj(dir + poses[p], kUnit, "firehik02", blade_[p]);
        std::vector<EffectCorner> strip;
        loadEffectObj(dir + poses[p], kUnit, "flamestani", strip);
        // The flip-book's four quarters down V, laid out once: the strip spans MU's first
        // quarter, and MU adds fV to it.
        for (int f = 0; f < kFlips; ++f) {
            flip_[p][f] = strip;
            for (EffectCorner& c : flip_[p][f]) c.v += float(f) * 0.25f;
        }
    }
    bladeBlend_.resize(blade_[0].size());
    flipBlend_.resize(flip_[0][0].size());
    bladeSheet_ = take(dir + "firehik02.png");
    flipSheet_ = take(dir + "flamestani.png");
    lava_ = take(dir + "lava.png");
    fire_[0] = take(dir + "firehik01.png");
    fire_[1] = take(dir + "firehik03.png");
    fire_[2] = bladeSheet_;
    const auto sheet = [&](const char* name) -> bgfx::TextureHandle {
        if (const content::EffectSheet* one = table.effect(name)) {
            return textures.load(assetDir + "/" + one->path, content::TextureRole::Albedo);
        }
        return BGFX_INVALID_HANDLE;
    };
    light_ = sheet("light");        // BITMAP_LIGHT, Effect/flare01
    white_ = sheet("trail_skill");  // BITMAP_BLUR + 2, Effect/motion_blur_r
    const bool whole = !blade_[0].empty() && blade_[0].size() == blade_[1].size() &&
                       flip_[0][0].size() == flip_[1][0].size() && bgfx::isValid(bladeSheet_);
    core::logf("flame strike: blade %s, ribbons %s/%s, body fire %s", whole ? "yes" : "NO",
               bgfx::isValid(white_) ? "yes" : "NO", bgfx::isValid(lava_) ? "yes" : "NO",
               bgfx::isValid(fire_[0]) ? "yes" : "NO");
    return whole;
}

bool FlameStrike::cast(const float feet[3], const float way[2], uint32_t caster_id) {
    if (playing_) return false;  // ours: one at a time (see the header)
    // MU's -Y along `way`, as Requiem lays Neil: the corner frame's Z on -way, its X his right.
    for (int k = 0; k < 3; ++k) feet_[k] = feet[k];
    z_[0] = -way[0];
    z_[1] = 0.0f;
    z_[2] = -way[1];
    x_[0] = way[1];
    x_[1] = 0.0f;
    x_[2] = -way[0];
    playing_ = true;
    caster_ = caster_id;
    owed_ = clock_ = 0.0f;
    frame_ = 0;
    key_ = 0.0f;
    alpha_ = 0.0f;
    whiteBlur_.live = lavaBlur_.live = false;
    whiteBlur_.count = lavaBlur_.count = 0;
    return true;
}

void FlameStrike::burn(uint32_t id) {
    Burning* free = nullptr;
    for (Burning& one : burning_) {
        if (one.id == id && one.left > 0) {
            one.left = 20;
            return;
        }
        if (free == nullptr && one.left <= 0) free = &one;
    }
    if (free != nullptr) *free = Burning{id, 20};
}

void FlameStrike::ribbonAt(const float table[][2][3], float key, float out[2][3]) const {
    float model[2][3];
    tableAt(table, key, model);
    for (int e = 0; e < 2; ++e) {
        for (int a = 0; a < 3; ++a) {
            out[e][a] = feet_[a] + (model[e][0] * x_[a] + model[e][1] * y_[a] +
                                    model[e][2] * z_[a]) * kUnit;
        }
    }
}

void FlameStrike::lay(Ribbon& ribbon, const float table[][2][3], float from) {
    // Ten samples across this frame's share of his pose, from last frame's key to this one's.
    const float span = key_ - from;
    for (int i = 1; i <= 10; ++i) {
        const float k = from + span * float(i) / 10.0f;
        if (k < 5.0f || k > 13.0f) continue;
        if (!ribbon.live) {
            ribbon.live = true;
            ribbon.life = 30;
            ribbon.count = 0;
        }
        const int keep = std::min(ribbon.count, kBlurMost - 1);
        std::memmove(ribbon.edges[1], ribbon.edges[0], sizeof(ribbon.edges[0]) * size_t(keep));
        ribbonAt(table, k, ribbon.edges[0]);
        ribbon.count = keep + 1;
    }
}

void FlameStrike::age(Ribbon& ribbon) {
    if (!ribbon.live) return;
    if (--ribbon.life <= 0) {
        ribbon.live = false;
        ribbon.count = 0;
        return;
    }
    ribbon.count = std::max(ribbon.count - 1, 0);
}

void FlameStrike::step() {
    // MoveObjectBlurs first: an edge given up a frame, all gone 30 frames after the first.
    age(whiteBlur_);
    age(lavaBlur_);
    const float from = key_;
    if (frame_ > 0) {
        // Move_MODEL_EFFECT_FLAME_STRIKE: in at +0.1 a frame, out at -0.1 once LifeTime < 20.
        const int life = 35 - frame_;
        alpha_ = life < 20 ? alpha_ - 0.1f : std::min(1.0f, alpha_ + 0.1f);
        key_ = std::min(13.0f, key_ + kSpeed);
    }
    // The ribbons between keys 5 and 13, ten samples a frame, while his pose still plays: it
    // ends at 13, and so do they.
    if (key_ > from && key_ >= 5.0f) {
        lay(whiteBlur_, kRibbonWhite, from);
        lay(lavaBlur_, kRibbonLava, from);
    }
    ++frame_;
    const bool bladeGone = frame_ > 15 && alpha_ < 0.1f;
    if (bladeGone && !whiteBlur_.live && !lavaBlur_.live) playing_ = false;
}

void FlameStrike::stepBody(const float at[3]) {
    // One orange flare for this frame, and one rising flame of the three.
    if (flareCount_ < int(sizeof(flares_) / sizeof(flares_[0]))) {
        for (int k = 0; k < 3; ++k) flares_[flareCount_].at[k] = at[k];
        ++flareCount_;
    }
    for (Flame& one : flames_) {
        if (one.alive) continue;
        one = Flame{};
        one.alive = true;
        one.sheet = uint8_t(std::min(2, int(unit() * 3.0f)));
        for (int k = 0; k < 3; ++k) one.at[k] = at[k];
        const float call = 1.3f + unit() * 0.4f;
        one.scale = call * (0.72f + unit() * 0.72f);
        one.rise = 6.4f + unit() * 2.4f;
        one.shrink = 0.05f + unit() * 0.02f;
        one.fadeIn = 0.2f + unit() * 0.1f;
        one.spin = unit() * 6.2831853f;
        const int lives[3][2] = {{27, 5}, {17, 5}, {12, 5}};
        one.life = lives[one.sheet][0] + int(unit() * float(lives[one.sheet][1]));
        return;
    }
}

void FlameStrike::drawRibbon(gfx::Effects& effects, const Ribbon& ribbon,
                             bgfx::TextureHandle sheet, float light) const {
    if (!ribbon.live || ribbon.count < 2 || !bgfx::isValid(sheet)) return;
    const float n = float(ribbon.count);
    for (int j = 0; j + 1 < ribbon.count; ++j) {
        const float l0 = (n - float(j)) / n, l1 = (n - float(j + 1)) / n;
        const float u0 = float(j) / n, u1 = float(j + 1) / n;
        gfx::Sprite sprite;
        sprite.placed = true;
        sprite.sheet = sheet;
        sprite.blend = gfx::Blend::Additive;
        // One light for the quad, its middle's: the pass colours a sprite, not a corner.
        const float lit = 0.5f * (l0 + l1) * light;
        sprite.colour[0] = sprite.colour[1] = sprite.colour[2] = lit;
        const auto& e = ribbon.edges;
        for (int k = 0; k < 3; ++k) {
            sprite.corner[0][k] = e[j][0][k];
            sprite.corner[1][k] = e[j][1][k];
            sprite.corner[2][k] = e[j + 1][1][k];
            sprite.corner[3][k] = e[j + 1][0][k];
            sprite.position[k] = 0.25f * (e[j][0][k] + e[j][1][k] + e[j + 1][0][k] + e[j + 1][1][k]);
        }
        const float uv[4][2] = {{u0, 1.0f}, {u0, 0.0f}, {u1, 0.0f}, {u1, 1.0f}};
        for (int k = 0; k < 4; ++k) {
            sprite.cornerUv[k][0] = uv[k][0];
            sprite.cornerUv[k][1] = uv[k][1];
        }
        effects.add(sprite);
    }
}

