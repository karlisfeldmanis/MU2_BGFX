void tableAt(const float table[][2][3], float key, float out[2][3]) {
    const float at = std::clamp(key, 0.0f, 13.0f) * 10.0f;
    const int a = std::min(int(at), 129);
    const float t = at - float(a);
    for (int e = 0; e < 2; ++e) {
        for (int k = 0; k < 3; ++k) {
            out[e][k] = table[a][e][k] + (table[a + 1][e][k] - table[a][e][k]) * t;
        }
    }
}

